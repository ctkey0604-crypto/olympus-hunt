const PROC_ICONS = {
  coin(x, y) {
    const d = Math.hypot(x - 7.5, y - 7.5);
    if (d <= 6.8) {
      if ((x === 7 || x === 8) && y >= 4 && y <= 11) return x === 8 ? 'A' : 'Y';
      if (d > 5.4) return (x + y) < 15 ? 'Y' : 'A';
      return 'y';
    }
  },
  pxc(x, y) {
    const d = Math.hypot(x - 7.5, y - 7.5);
    if (d <= 6.8) {
      const P = (x === 6 && y >= 4 && y <= 11) || (y === 4 && x >= 6 && x <= 9) || (y === 7 && x >= 6 && x <= 9) || (x === 9 && y >= 4 && y <= 7);
      if (P) return 'W';
      if (d > 5.4) return (x + y) < 15 ? 'p' : 'P';
      return 'p';
    }
  },
  index(x, y) {
    const d = Math.hypot(x - 7.5, y - 7.5);
    if (d <= 6.8) {
      if (d > 5.6) return 'k';
      const a = Math.atan2(y - 7.5, x - 7.5);
      if (a < -1.2) return 'y';
      if (a < 0.6) return 'g';
      if (a < 2.2) return 'u';
      return 'o';
    }
  },
};

